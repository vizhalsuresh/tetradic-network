import numpy as np
import soundfile as sf
import scipy.signal
import subprocess

def synthesize_cello_sul_tasto(sr, duration_sec):
    """
    Synthesize an ultra-warm, prestigious orchestral cello bow swell (Sul Tasto).
    Sul Tasto: Bow drawn gently across fingerboard.
    Characteristics: Rich low fundamentals (73Hz - 220Hz), zero harsh metallic harmonics,
    gentle 150ms bow hair grip swell, human vibrato (5.1 Hz), and spruce/maple body formants.
    """
    n_samples = int(duration_sec * sr)
    t = np.linspace(0, duration_sec, n_samples, endpoint=False)

    # 1. Cello chord partials: D2 (73.4Hz), A2 (110Hz), D3 (146.8Hz), F3 (174.6Hz), A3 (220Hz), D4 (293.7Hz)
    partials = [
        # (freq, relative_amp, decay_tau, pan_offset)
        (73.42,  0.45, 3.8,  0.00), # D2 fundamental - deep chest resonance
        (110.00, 0.38, 3.5, -0.12), # A2 fifth - rich cello body
        (146.83, 0.32, 3.2,  0.10), # D3 octave - velvety warm core
        (174.61, 0.22, 2.9, -0.08), # F3 minor 3rd - expressive warmth
        (220.00, 0.16, 2.6,  0.14), # A3 fifth - singing tone
        (293.66, 0.09, 2.2,  0.00), # D4 second octave - soft sheen
    ]

    # Human vibrato: begins ~250ms after bow stroke, 5.1 Hz, gentle depth
    vib_onset = np.clip((t - 0.25) / 0.5, 0.0, 1.0)
    vibrato = vib_onset * 0.008 * np.sin(2 * np.pi * 5.1 * t)

    # Bow attack swell: gentle 140ms rise (no percussive click!)
    attack_samples = int(0.14 * sr)
    attack_env = np.ones(n_samples)
    attack_env[:attack_samples] = 0.5 * (1.0 - np.cos(np.pi * np.linspace(0, 1, attack_samples)))

    # Overall sustain & slow fade envelope (unified with hero hold)
    fade_env = np.exp(-t / 1.7) * np.clip(1.0 - (t / (duration_sec - 0.05))**2.5, 0, 1)

    cello_l = np.zeros(n_samples)
    cello_r = np.zeros(n_samples)

    for freq, amp, tau, pan in partials:
        # Frequency with natural vibrato
        inst_freq = freq * (1.0 + vibrato)
        phase = 2 * np.pi * np.cumsum(inst_freq) / sr
        
        # Second harmonic overtone for natural string timbre
        wave = np.sin(phase) + 0.35 * np.sin(2 * phase) + 0.12 * np.sin(3 * phase)
        
        # Individual decay
        part_decay = np.exp(-t / tau)
        signal = wave * amp * part_decay * attack_env * fade_env
        
        p_l = 0.5 - pan
        p_r = 0.5 + pan
        cello_l += signal * p_l
        cello_r += signal * p_r

    # 2. Tactile bow hair breath (pink noise filtered around 220Hz wood resonance, very subtle)
    np.random.seed(42)
    noise = np.random.randn(n_samples)
    # Bandpass filter around 220 Hz
    b, a = scipy.signal.butter(2, [140 / (sr/2), 320 / (sr/2)], btype='band')
    bow_breath = scipy.signal.lfilter(b, a, noise) * 0.028 * attack_env * fade_env
    cello_l += bow_breath * 0.5
    cello_r += bow_breath * 0.5

    # 3. Warm Cello Body Formant EQ (2nd-order peak filter boosting 180Hz chest warmth, rolling off everything > 1.2kHz)
    b_low, a_low = scipy.signal.butter(2, 950 / (sr/2), btype='low')
    cello_l = scipy.signal.lfilter(b_low, a_low, cello_l)
    cello_r = scipy.signal.lfilter(b_low, a_low, cello_r)

    return np.column_stack([cello_l, cello_r])

def main():
    sr = 48000
    duration = 12.0
    total_samples = int(duration * sr)
    bam_time = 7.50
    bam_idx = int(bam_time * sr)

    print("--- 1. Loading Pre-BAM Acoustic Guitar Strum Track ---")
    # Load original acoustic track generated by MusicGen
    # Re-run or read from the master 12s wav prior to chime modification
    orig_wav, file_sr = sf.read('public/audio/blueprint_master_guitar_strum_12s.wav')
    assert file_sr == sr

    # We isolate the pre-BAM portion (0.0s to 7.50s) which has the beloved guitar strumming & clock ticks
    master_guitar = orig_wav.copy()

    # Post-BAM time
    post_samples = total_samples - bam_idx
    t_post = np.linspace(0, post_samples / sr, post_samples, endpoint=False)

    # Unified slow fade envelope
    fade_env = np.exp(-t_post / 1.7) * np.clip(1.0 - (t_post / 4.45)**2.5, 0, 1)

    # Warm Dm9 guitar sustain chord (pure acoustic wood body, zero high treble)
    sustain_chord = np.zeros(post_samples)
    chord_partials = [
        (146.83, 0.40, 3.5), # D3 (warm acoustic body)
        (220.00, 0.35, 3.2), # A3
        (349.23, 0.28, 2.8), # F4 (minor warmth)
        (440.00, 0.22, 2.5), # A4
        (523.25, 0.16, 2.2), # C5 (7th)
    ]
    for freq, amp, tau in chord_partials:
        decay = np.exp(-t_post / tau)
        sustain_chord += np.sin(2 * np.pi * freq * t_post) * decay * amp * 0.15

    # Guitar post-BAM: End active rhythmic strumming, keep warm sustain chord fading together
    guitar_post_l = master_guitar[bam_idx:, 0] * 0.20 * fade_env + sustain_chord * fade_env
    guitar_post_r = master_guitar[bam_idx:, 1] * 0.20 * fade_env + sustain_chord * fade_env

    # Low-pass filter post-BAM guitar at 1.4kHz to eliminate any residual chime frequencies
    b_lp, a_lp = scipy.signal.butter(2, 1400 / (sr/2), btype='low')
    guitar_post_l = scipy.signal.lfilter(b_lp, a_lp, guitar_post_l)
    guitar_post_r = scipy.signal.lfilter(b_lp, a_lp, guitar_post_r)

    master = np.zeros((total_samples, 2))
    master[:bam_idx, :] = master_guitar[:bam_idx, :]
    master[bam_idx:, 0] = guitar_post_l
    master[bam_idx:, 1] = guitar_post_r

    print("--- 2. Synthesizing Warm Orchestral Cello Sul Tasto Swell ---")
    cello_swell = synthesize_cello_sul_tasto(sr, post_samples / sr)

    # Layer Cello Swell into post-BAM region
    master[bam_idx:, 0] += cello_swell[:, 0] * 0.95
    master[bam_idx:, 1] += cello_swell[:, 1] * 0.95

    # Reinforce the 48Hz Sub-Bass BAM at 7.50s for physical weight
    bam_len = int(2.0 * sr)
    t_bam = np.linspace(0, 2.0, bam_len)
    sub_drop = np.sin(2 * np.pi * (48 * np.exp(-t_bam * 2.2)) * t_bam) * np.exp(-t_bam * 1.6) * 0.65
    master[bam_idx:bam_idx+bam_len, 0] += sub_drop
    master[bam_idx:bam_idx+bam_len, 1] += sub_drop

    # Normalize cleanly
    peak = np.max(np.abs(master))
    print(f"Master peak before normalization: {peak:.3f}")
    if peak > 0.92:
        master = master / peak * 0.90

    # Save to master audio paths
    wav_path = 'public/audio/blueprint_master_guitar_strum_12s.wav'
    mp3_path = 'public/audio/blueprint_master_guitar_strum_12s.mp3'

    sf.write(wav_path, master, sr)
    print(f"Saved master WAV: {wav_path}")

    subprocess.run([
        'ffmpeg', '-y', '-i', wav_path,
        '-codec:a', 'libmp3lame', '-b:a', '320k',
        mp3_path
    ], check=True)
    print(f"Generated 320kbps MP3: {mp3_path}")

    # Synchronize fallback paths
    subprocess.run([
        'ffmpeg', '-y', '-i', wav_path,
        '-codec:a', 'libmp3lame', '-b:a', '320k',
        'public/audio/blueprint_master_guitar_strum.mp3'
    ], check=True)
    subprocess.run([
        'ffmpeg', '-y', '-i', wav_path,
        '-codec:a', 'libmp3lame', '-b:a', '320k',
        'public/audio/blueprint_master_rising_score.mp3'
    ], check=True)

    # Copy to artifacts directory
    artifact_mp3 = '/home/revenant/.gemini/antigravity/brain/e7c9dc1f-6305-464e-8322-b0b88de2e48b/blueprint_master_guitar_strum_12s.mp3'
    subprocess.run(['cp', mp3_path, artifact_mp3], check=True)
    print(f"Copied master audio to artifacts: {artifact_mp3}")

    # Inspect rms in the tail
    rms_10_11 = np.sqrt(np.mean(master[int(10.0*sr):int(11.0*sr)]**2))
    rms_11_12 = np.sqrt(np.mean(master[int(11.0*sr):int(11.95*sr)]**2))
    print(f"RMS at 10-11s: {rms_10_11:.5f}")
    print(f"RMS at 11-12s: {rms_11_12:.5f}")
    print("✅ Cello swell and slow fade successfully synthesized!")

if __name__ == '__main__':
    main()
